// Returns the embedded SPIR-V bytes for "triangle.slang.vertex" etc.
std::vector<std::uint8_t> const* embeddedSpirv(std::string const& name) {
    static std::vector<std::vector<std::uint8_t>> storage;
    static bool initialized = false;
    if (!initialized) {
        for (std::size_t i = 0; i < helios::shaders::embedded::kShaderCount; ++i) {
            auto const& s = helios::shaders::embedded::kShaders[i];
            storage.emplace_back(s.data, s.data + s.size);
        }
        initialized = true;
    }
    for (auto const& s : storage) {
        // storage order matches kShaders order
        (void)s;
    }
    for (std::size_t i = 0; i < helios::shaders::embedded::kShaderCount; ++i) {
        if (helios::shaders::embedded::kShaders[i].name == name) {
            return &storage[i];
        }
    }
    return nullptr;
}

struct SpvModule {
    SpvModule() = default;
    ~SpvModule() {
        spvReflectDestroyShaderModule(&module);
    }
    SpvModule(SpvModule const&) = delete;
    SpvModule& operator=(SpvModule const&) = delete;

    bool load(std::vector<std::uint8_t> const& bytes) {
        data = bytes;
        return spvReflectCreateShaderModule(data.size(), data.data(), &module) == SPV_REFLECT_RESULT_SUCCESS;
    }

    std::vector<std::uint8_t> data;
    SpvReflectShaderModule module{};
};

