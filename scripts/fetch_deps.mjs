// Helios dependency fetcher — downloads pinned immutable revisions, verifies SHA-256,
// extracts into .deps-cache/, and optionally writes cmake/deps-cache.cmake.
// Usage: node scripts/fetch_deps.mjs [--update-lock] [--force] [--write-cmake]
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const lockPath = path.join(root, 'cmake', 'deps.lock.json');
const lock = JSON.parse(fs.readFileSync(lockPath, 'utf8'));
const updateLock = process.argv.includes('--update-lock');
const skipExisting = !process.argv.includes('--force');

function sha256File(p) { return createHash('sha256').update(fs.readFileSync(p)).digest('hex'); }

function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, ...opts });
  if (r.status !== 0) throw new Error(cmd + ' ' + args.join(' ') + ' failed: ' + String(r.stderr || r.stdout || '').slice(0, 2000));
  return r.stdout;
}

async function download(url, dest) {
  const res = await fetch(url, { headers: { 'User-Agent': 'helios-bootstrap' }, redirect: 'follow' });
  if (!res.ok) throw new Error('HTTP ' + res.status + ' for ' + url);
  fs.writeFileSync(dest, Buffer.from(await res.arrayBuffer()));
}

const results = [];
for (const [name, e] of Object.entries(lock.entries)) {
  try {
    if (e.kind === 'file') {
      const dest = path.join(root, ...e.dest.split('/'));
      const done = fs.existsSync(dest) && e.sha256 && sha256File(dest) === e.sha256;
      if (done && skipExisting) { results.push(name + ': cached OK'); continue; }
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      await download(e.url, dest);
      const h = sha256File(dest);
      if (e.sha256 && h !== e.sha256) throw new Error(name + ': hash mismatch ' + h);
      e.sha256 = h;
      results.push(name + ': downloaded (' + h.slice(0, 12) + '...)');
    } else {
      const cacheDir = path.join(root, ...e.cache_dir.split('/'));
      const stamp = path.join(cacheDir, '.fetch-ok');
      const done = fs.existsSync(stamp) && e.sha256 && fs.readFileSync(stamp, 'utf8').trim() === e.sha256;
      if (done && skipExisting) { results.push(name + ': cached OK'); continue; }
      const tmp = path.join(root, '.deps-cache', '_tmp_' + name);
      fs.mkdirSync(path.join(root, '.deps-cache'), { recursive: true });
      await download(e.url, tmp);
      const h = sha256File(tmp);
      if (e.sha256 && h !== e.sha256) throw new Error(name + ': hash mismatch ' + h);
      e.sha256 = h;
      fs.rmSync(cacheDir, { recursive: true, force: true });
      fs.mkdirSync(cacheDir, { recursive: true });
      run('tar', ['-xf', tmp, '-C', cacheDir]);
      const entries = fs.readdirSync(cacheDir);
      if (entries.length === 1) {
        const inner = path.join(cacheDir, entries[0]);
        for (const f of fs.readdirSync(inner)) fs.renameSync(path.join(inner, f), path.join(cacheDir, f));
        fs.rmSync(inner, { recursive: true, force: true });
      }
      fs.rmSync(tmp, { force: true });
      fs.writeFileSync(stamp, h);
      results.push(name + ': downloaded+extracted (' + h.slice(0, 12) + '...)');
    }
  } catch (err) {
    results.push(name + ': FAILED - ' + err.message);
  }
}

if (updateLock) {
  fs.writeFileSync(lockPath, JSON.stringify(lock, null, 2) + '\n');
  console.log('Lock file updated.');
}

if (process.argv.includes('--write-cmake')) {
  const cacheDir = path.join(root, '.deps-cache');
  const lines = [
    '# Generated by scripts/fetch_deps.mjs --write-cmake. Do not edit.',
    'set(HELIOS_DEPS_CACHE_DIR "' + cacheDir.replace(/\\/g, '/') + '")',
  ];
  for (const [name, e] of Object.entries(lock.entries)) {
    if (e.kind === 'archive') {
      lines.push('set(FETCHCONTENT_SOURCE_DIR_' + name.toUpperCase() + ' "' + path.join(cacheDir, e.cache_dir.split('/')[1]).replace(/\\/g, '/') + '")');
    }
  }
  const slangDir = {
    win32: 'slang-windows-x64',
    linux: 'slang-linux-x64',
    darwin: process.arch === 'arm64' ? 'slang-macos-arm64' : 'slang-macos-x64',
  }[process.platform];
  if (slangDir && fs.existsSync(path.join(cacheDir, slangDir, 'bin'))) {
    lines.push('set(HELIOS_SLANG_BIN_DIR "' + path.join(cacheDir, slangDir, 'bin').replace(/\\/g, '/') + '")');
  }
  fs.writeFileSync(path.join(root, 'cmake', 'deps-cache.cmake'), lines.join('\n') + '\n');
  console.log('cmake/deps-cache.cmake written');
}

console.log(results.join('\n'));
const failed = results.filter(r => r.includes('FAILED'));
if (failed.length) { console.log('FAILURES: ' + failed.length); process.exit(1); }
